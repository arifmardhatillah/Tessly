// Bahasa diingat per komputer. Bawaan: Indonesia.
let LANG = 'id';
try {
  const l = localStorage.getItem('tessly.lang');
  if (DICT[l]) LANG = l;
} catch { /* tanpa penyimpanan: bahasa bawaan */ }

function t(key, vars) {
  const s = DICT[LANG][key] ?? DICT.id[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s;
}

// Pasang teks pada elemen yang ditandai di HTML.
function applyStaticText() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach((n) => {
    const s = t(n.dataset.i18nAria);
    n.setAttribute('aria-label', s);
    if (n.hasAttribute('title')) n.title = s;
  });
}
